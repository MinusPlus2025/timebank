export function detectLang(): Lang {
  return navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function formatMinutes(min: number, s: Strings) {
  const h = Math.floor(min / 60);
  const hours = `${h} ${h === 1 ? s.hour : s.hoursUnit}`;
  if (min % 60 === 0) return hours;
  if (min < 60) return `${min} ${s.minutesUnit}`;
  return `${hours} ${min % 60} ${s.minutesUnit}`;
}

export const formatHours = (min: number) => (min % 60 === 0 ? String(min / 60) : (min / 60).toFixed(1));
